import type { Express } from "express";
import { route } from "../middleware/endpoint.js";
import {
  overviewController,
  forecastController,
  refreshController,
  configureMonitoringController,
  bandsController,
  configureBandsController,
  warningsController,
  warningController,
  notificationsController,
  readNotificationController,
} from "../controllers/monitoring.controller.js";
export function monitoringRoutes(app: Express) {
  route(
    app,
    "get",
    "/staff/distribution/monitoring",
    "staff",
    overviewController,
  );
  route(
    app,
    "get",
    "/staff/pickup-sites/:id/forecast",
    "staff",
    forecastController,
  );
  route(
    app,
    "post",
    "/staff/pickup-sites/:id/forecast/refresh",
    "staff",
    refreshController,
  );
  route(
    app,
    "patch",
    "/staff/pickup-sites/:id/monitoring",
    "staff",
    configureMonitoringController,
  );
  route(
    app,
    "get",
    "/staff/distribution/warnings",
    "staff",
    warningsController,
  );
  route(
    app,
    "get",
    "/staff/distribution/warnings/:id",
    "staff",
    warningController,
  );
  route(
    app,
    "get",
    "/staff/distribution/temperature-bands",
    "staff",
    bandsController,
  );
  route(
    app,
    "patch",
    "/staff/distribution/temperature-bands",
    "admin",
    configureBandsController,
  );
  route(
    app,
    "get",
    "/staff/distribution/notifications",
    "staff",
    notificationsController,
  );
  route(
    app,
    "post",
    "/staff/distribution/notifications/:id/read",
    "staff",
    readNotificationController,
  );
}
